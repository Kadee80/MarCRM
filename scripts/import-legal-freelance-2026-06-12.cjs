async function main() {
  console.log(`\nLegal Freelance import 2026-06-12 — ${LEADS.length} leads\n`);
  let created = 0;
  let skipped = 0;

  for (const lead of LEADS) {
    const existing = await prisma.company.findFirst({
      where: { name: lead.company.name },
    });

    if (existing) {
      console.log(`  SKIP  (exists)  ${lead.company.name}`);
      skipped++;
      continue;
    }

    const company = await prisma.company.create({
      data: {
        ...lead.company,
        contacts: {
          create: lead.contacts.map((c) => ({
            name: c.name,
            title: c.title,
            persona: c.persona,
            decisionMaker: c.decisionMaker,
            linkedin: c.linkedin,
          })),
        },
        scrapeResults: {
          create: [
            {
              pipeline: "legal-freelance",
              url: lead.scrape.url,
              source: lead.scrape.source,
              matchedSignals: lead.scrape.matchedSignals,
              scrapeDate: new Date("2026-06-12"),
            },
          ],
        },
      },
    });

    console.log(
      `  CREATE          ${company.name}  (fit ${lead.company.fitScore} / intent ${lead.company.intentScore})`
    );
    created++;
  }

  console.log(`\nDone. Created ${created}, skipped ${skipped}.\n`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
