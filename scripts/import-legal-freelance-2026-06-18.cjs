async function main() {
  console.log("\n⚖️  Legal Freelance Import — 2026-06-18");
  console.log("   Pipeline: legal-freelance");
  console.log(`   Leads to process: ${LEADS.length}\n`);

  let created = 0;
  let skipped = 0;

  for (const lead of LEADS) {
    // Deduplicate by company name
    const existing = await prisma.company.findFirst({
      where: { name: lead.company.name },
    });

    if (existing) {
      console.log(`  SKIP  ${lead.company.name} (already in CRM)`);
      skipped++;
      continue;
    }

    // Create Company
    const company = await prisma.company.create({
      data: {
        name: lead.company.name,
        website: lead.company.website,
        pipeline: lead.company.pipeline,
        industry: lead.company.industry,
        size: lead.company.size,
        location: lead.company.location,
        fundingStage: lead.company.fundingStage,
        techStack: lead.company.techStack,
        fitScore: lead.company.fitScore,
        intentScore: lead.company.intentScore,
        fitDetails: lead.company.fitDetails,
        intentDetails: lead.company.intentDetails,
        vertical: lead.company.vertical,
        subvertical: lead.company.subvertical,
        engagementModel: lead.company.engagementModel,
        buyerType: lead.company.buyerType,
        compensationText: lead.company.compensationText,
        remoteFlag: lead.company.remoteFlag,
        employmentTypeRaw: lead.company.employmentTypeRaw,
        urgencyScore: lead.company.urgencyScore,
        starred: lead.company.starred,
        notes: lead.company.notes,
        source: lead.company.source,
        lastActivity: lead.company.lastActivity,
      },
    });

    // Create Contacts
    for (const contact of lead.contacts) {
      await prisma.contact.create({
        data: {
          companyId: company.id,
          name: contact.name,
          title: contact.title,
          persona: contact.persona,
          decisionMaker: contact.decisionMaker,
          email: contact.email || "",
          linkedin: contact.linkedin || "",
        },
      });
    }

    // Create ScrapeResult log
    await prisma.scrapeResult.create({
      data: {
        pipeline: "legal-freelance",
        url: lead.scrape.url,
        source: lead.scrape.source,
        matchedSignals: lead.scrape.matchedSignals,
        resultData: JSON.stringify({
          companyName: lead.company.name,
          scrapeDate: "2026-06-18",
          fitScore: lead.company.fitScore,
          intentScore: lead.company.intentScore,
        }),
        imported: true,
      },
    });

    console.log(
      `  CREATE  ${lead.company.name}  (fit ${lead.company.fitScore} / intent ${lead.company.intentScore} = ${lead.company.fitScore + lead.company.intentScore})`
    );
    created++;
  }

  console.log(`\n  Done. Created ${created}, skipped ${skipped}.\n`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
