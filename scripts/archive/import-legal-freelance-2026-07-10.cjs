#!/usr/bin/env node
/**
 * Import leads from Legal Freelance pipeline scrape 2026-07-10
 *
 * Usage:  cd MarCRM && node scripts/import-legal-freelance-2026-07-10.cjs
 *
 * - All leads have pipeline="legal-freelance"
 * - Deduplicates by company name (skips if already in DB)
 * - Creates Company + Contact records, logs a ScrapeResult per lead
 *
 * NOTE (2026-07-10): This is a NO-OP import. The 2026-07-10 scrape produced
 * zero new leads that cleared the 55+ include threshold after dedup + scoring
 * (saturated-pipeline day). The LEADS array is intentionally empty; running
 * this script is safe and will insert nothing. One watchlist near-miss
 * (ACC Jobline #53153 — Commercial Contracts Attorney, In-House, Remote,
 * scored 45) is recorded in the report JSON/MD but deliberately NOT imported.
 *
 * NOTE: Neon DB is unreachable from the Cowork sandbox, so this script is
 * generated by the scrape but must be run from Katie's local machine where
 * DATABASE_URL points to the Neon production instance.
 */

const { PrismaClient } = require("@prisma/client");
const prisma = new PrismaClient();

const SCRAPE_DATE = "2026-07-10";
const PIPELINE = "legal-freelance";

const LEADS = [
  // No qualifying leads (55+) this run — saturated-pipeline day.
];

async function main() {
  console.log(`\n=== Legal Freelance Import — ${SCRAPE_DATE} ===`);
  console.log(`Pipeline: ${PIPELINE}`);
  console.log(`Leads to process: ${LEADS.length}\n`);

  if (LEADS.length === 0) {
    console.log("No new leads to import for this date (0 qualifying after dedup + scoring). Nothing to do.");
    await prisma.$disconnect();
    return;
  }

  let created = 0;
  let skipped = 0;
  let errors = 0;

  for (const lead of LEADS) {
    const { company, contacts, scrape } = lead;
    try {
      const existing = await prisma.company.findFirst({
        where: { name: company.name },
      });

      if (existing) {
        console.log(`⏭️  SKIP (exists): ${company.name}`);
        skipped += 1;
        continue;
      }

      const createdCompany = await prisma.company.create({
        data: {
          ...company,
          contacts: {
            create: contacts.map((c) => ({
              name: c.name,
              title: c.title,
              linkedin: c.linkedin || "",
              persona: c.persona || "",
              decisionMaker: c.decisionMaker || false,
            })),
          },
        },
      });

      await prisma.scrapeResult.create({
        data: {
          url: scrape.url,
          source: scrape.source,
          pipeline: PIPELINE,
          matchedSignals: scrape.matchedSignals,
          resultData: JSON.stringify({ ...company, scrapeDate: SCRAPE_DATE }),
          imported: true,
        },
      });

      console.log(
        `✅ CREATED: ${createdCompany.name} (id=${createdCompany.id}, fit=${company.fitScore}, intent=${company.intentScore})`,
      );
      created += 1;
    } catch (err) {
      console.error(`❌ ERROR on ${company.name}:`, err.message);
      errors += 1;
    }
  }

  console.log(`\n=== Summary ===`);
  console.log(`Created: ${created}`);
  console.log(`Skipped (duplicate): ${skipped}`);
  console.log(`Errors: ${errors}`);

  await prisma.$disconnect();
}

main().catch(async (err) => {
  console.error("Fatal:", err);
  await prisma.$disconnect();
  process.exit(1);
});
